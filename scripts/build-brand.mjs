#!/usr/bin/env node
// Derives the brand files from the vendored Kopimi "K" (src/brand/kopimi-k.svg, public domain, see src/brand/README.md) and writes them to
// src/brand/: the path data BrandMark.vue draws (mark.ts), favicon.svg, and the PNG and ICO fallbacks. The outputs are committed, so a normal
// build needs nothing from here; run `npm run build:brand` only when the source mark changes (it needs @resvg/resvg-js, MPL-2.0, a libre
// SVG renderer). `npm test` checks that the committed files match what this script writes.
//
// The source draws a black silhouette with a white stroke and white rhombus tops. Here the tops become real holes (one path, even-odd), so the
// mark has no background of its own and takes any colour: `currentColor` in the page, the accent in the favicon.
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { Resvg } from '@resvg/resvg-js'

const dir = join(import.meta.dirname, '..', 'src', 'brand')
const source = readFileSync(join(dir, 'kopimi-k.svg'), 'utf8')
const [silhouette, tops] = [...source.matchAll(/ d="([^"]+)"/g)].map((m) => m[1])
if (!silhouette || !tops) throw new Error('kopimi-k.svg: expected two paths')

/** A square box around the mark (it spans x -70..684, y 6..786 in the source's units), with room for the halo. */
export const VIEW_BOX = '-88 1 790 790'
// The second path's leading relative `m` is relative to the origin in its own element, but to the previous subpath's start once they are joined:
// make it absolute.
export const PATH = `${silhouette} ${tops.replace(/^m/, 'M')}`
export const ACCENT = { light: '#86321d', dark: '#e79475' } // the design tokens' terracotta 500 and 300, the accent in each colour mode

const svg = (body, extra = '') => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${VIEW_BOX}"${extra}>${body}</svg>\n`
const markPath = (attrs) => `<path d="${PATH}" fill-rule="evenodd" ${attrs}/>`

/** The favicon: the mark in the accent of the visitor's colour mode, on a transparent background. */
const favicon = svg(
  `<style>path{fill:${ACCENT.light}}@media (prefers-color-scheme:dark){path{fill:${ACCENT.dark}}}</style>${markPath('')}`,
)
/** For raster files, which cannot switch with the mode: the light accent inside a white outline, so it reads on a light or a dark tab. */
const raster = svg(`<path d="${silhouette}" fill="#fff" stroke="#fff" stroke-width="30" stroke-linejoin="round"/>${markPath(`fill="${ACCENT.light}"`)}`)

const png = (size) => new Resvg(raster, { fitTo: { mode: 'width', value: size } }).render().asPng()

/** An ICO file holding PNG images (supported since Windows Vista and by every browser). */
function ico(sizes) {
  const images = sizes.map((s) => png(s))
  const head = Buffer.alloc(6 + 16 * images.length)
  head.writeUInt16LE(0, 0)
  head.writeUInt16LE(1, 2)
  head.writeUInt16LE(images.length, 4)
  let offset = head.length
  images.forEach((img, i) => {
    const o = 6 + 16 * i
    head[o] = sizes[i] >= 256 ? 0 : sizes[i]
    head[o + 1] = head[o]
    head.writeUInt16LE(1, o + 4)
    head.writeUInt16LE(32, o + 6)
    head.writeUInt32LE(img.length, o + 8)
    head.writeUInt32LE(offset, o + 12)
    offset += img.length
  })
  return Buffer.concat([head, ...images])
}

export function outputs() {
  return {
    'mark.ts': `// Generated by scripts/build-brand.mjs from kopimi-k.svg: do not edit.\nexport const MARK_VIEW_BOX = '${VIEW_BOX}'\nexport const MARK_PATH = '${PATH}'\n`,
    'files/favicon.svg': favicon,
    'files/favicon.ico': ico([16, 32, 48]),
    'files/apple-touch-icon.png': png(180),
    'files/icon-192.png': png(192),
    'files/icon-512.png': png(512),
  }
}

export const sourceHash = () => createHash('sha256').update(readFileSync(join(dir, 'kopimi-k.svg'))).digest('hex')

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  mkdirSync(join(dir, 'files'), { recursive: true })
  for (const [name, data] of Object.entries(outputs())) writeFileSync(join(dir, name), data)
  console.log(`brand files written from kopimi-k.svg (${sourceHash().slice(0, 12)})`)
}
